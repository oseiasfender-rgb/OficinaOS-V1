import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
const base=path.dirname(fileURLToPath(import.meta.url));
const [keyFile,outputFile]=process.argv.slice(2);
if(!keyFile||!outputFile)throw new Error('Uso: node restore-official-backup.mjs /caminho/chave.txt /caminho/backup.json');
const manifest=JSON.parse(await fs.readFile(path.join(base,'manifest.json'),'utf8'));
const keyText=(await fs.readFile(keyFile,'utf8')).trim();
if(!/^[a-f0-9]{64}$/.test(keyText))throw new Error('Chave inválida.');
const parts=await Promise.all(manifest.parts.map(p=>fs.readFile(path.join(base,p),'utf8')));
const encrypted=Buffer.from(parts.join('').replace(/\s/g,''),'base64');
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
if(sha(encrypted)!==manifest.encryptedSha256)throw new Error('Integridade do conteúdo criptografado inválida.');
const decipher=crypto.createDecipheriv('aes-256-gcm',Buffer.from(keyText,'hex'),Buffer.from(manifest.ivBase64,'base64'));
decipher.setAAD(Buffer.from(manifest.sourceSha256,'hex'));
decipher.setAuthTag(Buffer.from(manifest.authTagBase64,'base64'));
const bytes=Buffer.concat([decipher.update(encrypted),decipher.final()]);
if(bytes.length!==manifest.sourceBytes||sha(bytes)!==manifest.sourceSha256)throw new Error('Integridade do backup original inválida.');
await fs.writeFile(outputFile,bytes,{flag:'wx',mode:0o600});
console.log('Backup original restaurado. SHA-256: '+sha(bytes));
